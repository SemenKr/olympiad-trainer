import type { ProblemDefinition } from "./problem-catalog";

// Explicit allowlist: this module must never project assessment answers,
// protected teaching text, checkpoint correctness or provenance.
export function browserProblemMetadata(problems: readonly ProblemDefinition[]) {
  return Object.fromEntries(
    problems.map((problem) => [
      problem.id,
      {
        id: problem.id,
        title: problem.title,
        hints: problem.hints.map((hint) => hint.id),
        solution: problem.solution.id,
        ...(problem.assessment.kind === "multiple-choice-set"
          ? { optionIds: problem.assessment.options.map((option) => option.id) }
          : {}),
      },
    ]),
  );
}

export function renderBrowserProblemMetadata(
  problems: readonly ProblemDefinition[],
) {
  return `// Generated by pnpm content:generate. Do not edit.\nexport const browserProblemMetadata = ${JSON.stringify(browserProblemMetadata(problems), null, 2)} as const;\n`;
}
